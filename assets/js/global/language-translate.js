export function updateContent(lang) {
    const t = translations[lang.trim().toUpperCase()];
    if (!t) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const value = t[el.getAttribute('data-i18n')];
        if (value !== undefined) el.innerHTML = value.replace('{year}', new Date().getFullYear());
    });

    document.querySelectorAll('.project-card').forEach((card, index) => {
        const id = index + 1;
        if (t[`project_${id}_title`]) card.setAttribute('data-title', t[`project_${id}_title`]);
        if (t[`project_${id}_desc`])  card.setAttribute('data-desc',  t[`project_${id}_desc`]);
    });
}

export function detectBrowserLanguage() {
    const lang = (navigator.language || navigator.userLanguage || 'pt').toLowerCase();
    if (lang.startsWith('pt')) return 'PT';
    if (lang.startsWith('es')) return 'ES';
    return 'EN';
}
